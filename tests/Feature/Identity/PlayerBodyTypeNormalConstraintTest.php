<?php

namespace Tests\Feature\Identity;

use App\Modules\Identity\Domain\Enums\UserParticipationRoleAssignerEnum;
use App\Modules\Identity\Domain\Enums\UserParticipationRoleEnum;
use App\Modules\Identity\Domain\Enums\UserParticipationRoleStatusEnum;
use App\Modules\Identity\Domain\Models\User;
use Illuminate\Foundation\Testing\RefreshDatabase;
use Illuminate\Support\Facades\DB;
use Tests\TestCase;

final class PlayerBodyTypeNormalConstraintTest extends TestCase
{
    use RefreshDatabase;

    public function test_existing_postgresql_player_profiles_accept_normal_after_constraint_upgrade(): void
    {
        if (DB::getDriverName() !== 'pgsql') {
            $this->markTestSkipped('Checks the PostgreSQL constraint on existing databases.');
        }

        $user = User::factory()->create();
        $user->participationRoles(false)->create([
            'role' => UserParticipationRoleEnum::PLAYER,
            'status' => UserParticipationRoleStatusEnum::ACTIVE,
            'assigned_at' => now(),
            'assigned_by' => $user->id,
            'assigner' => UserParticipationRoleAssignerEnum::USER,
        ]);

        // Reproduce the constraint generated by the original July migration,
        // before normal was introduced in the PHP enum in task 054.
        DB::statement('ALTER TABLE player_profiles DROP CONSTRAINT IF EXISTS player_profiles_body_type_check');
        DB::statement("ALTER TABLE player_profiles ADD CONSTRAINT player_profiles_body_type_check CHECK (body_type IN ('slim', 'large', 'athletic', 'muscular', 'stocky'))");

        $migration = require database_path('migrations/2026_10_29_120000_extend_player_body_type_normal_constraint.php');
        $migration->up();

        $definition = DB::selectOne("
            SELECT pg_get_constraintdef(c.oid) AS definition
            FROM pg_constraint c
            WHERE c.conrelid = 'player_profiles'::regclass
              AND c.conname = 'player_profiles_body_type_check'
        ");
        $this->assertNotNull($definition);
        $this->assertStringContainsString('normal', $definition->definition);

        $this->actingAs($user)->patch(route('account.player-profile.update'), [
            'section' => 'physical',
            'height_cm' => 185,
            'weight_kg' => 80,
            'body_type' => 'normal',
            'character' => [
                'uniform_kit' => 'mskba_home',
                'shoes' => 'blue',
            ],
        ])->assertRedirect()->assertSessionHasNoErrors();

        $this->assertDatabaseHas('player_profiles', [
            'user_id' => $user->id,
            'body_type' => 'normal',
        ]);
    }
}
