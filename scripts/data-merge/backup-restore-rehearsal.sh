#!/usr/bin/env bash
# Isolated backup/restore rehearsal. No mutations to either source DB.
set -euo pipefail

[[ $# -eq 2 ]] || { echo 'Usage: prod|dev run-id' >&2; exit 2; }
SCOPE="$1"
RUN_ID="$2"
[[ "$RUN_ID" =~ ^[0-9]+$ ]] || exit 2
case "$SCOPE" in
  prod)
    WORKTREE=/var/www/mskba
    EXPECTED_URL=https://mskba.ru
    EXPECTED_ENV=production
    COMPOSE='docker compose -f compose.yaml -f compose.prod.yaml'
    ;;
  dev)
    WORKTREE=/var/www/mskba-dev-next
    EXPECTED_URL=https://dev.mskba.ru
    EXPECTED_ENV=staging
    COMPOSE='docker compose --env-file .env -f compose.dev.yaml -f compose.dev.local.yaml'
    ;;
  *)
    echo 'Unknown scope' >&2
    exit 2
    ;;
esac
cd "$WORKTREE"
test -f .env
grep -Fxq "APP_URL=$EXPECTED_URL" .env
grep -Fxq "APP_ENV=$EXPECTED_ENV" .env
if [[ "$SCOPE" == dev ]]; then test -f compose.dev.local.yaml; fi

umask 077
ROOT=/home/deploy/mskba-data-merge-backups
DEST="$ROOT/$RUN_ID/$SCOPE"
if [[ -e "$DEST" ]]; then echo 'Destination exists; no overwrite' >&2; exit 3; fi
mkdir -p "$DEST"
chmod 700 "$ROOT" "$ROOT/$RUN_ID" "$DEST"
DUMP="$DEST/database.pgdump"
MEDIA="$DEST/storage-app.tar.gz"
# Remove only this script's incomplete temporary files if any stage fails.
trap 'rm -f "$DUMP.part" "$MEDIA.part"' EXIT

# Source database is queried by pg_dump only. Binary stays server-side.
$COMPOSE exec -T db sh -ceu 'exec env PGPASSWORD="$POSTGRES_PASSWORD" pg_dump --format=custom --no-owner --no-acl -U "$POSTGRES_USER" -d "$POSTGRES_DB"' > "$DUMP.part"
test -s "$DUMP.part"
mv "$DUMP.part" "$DUMP"
test -d storage/app
# The deploy host user cannot read all private originals. Stream the tar from
# the existing PHP container as root, without chmod/chown or webroot writes.
$COMPOSE exec -T --user 0:0 phpfpm sh -ceu 'cd /var/www/html && exec tar -czf - storage/app' > "$MEDIA.part"
test -s "$MEDIA.part"
mv "$MEDIA.part" "$MEDIA"
tar -tzf "$MEDIA" > /dev/null
sha256sum "$DUMP" "$MEDIA" > "$DEST/SHA256SUMS"
chmod 600 "$DUMP" "$MEDIA" "$DEST/SHA256SUMS"

# Network-isolated, disposable PostgreSQL without source volumes/ports.
CONTAINER="mskba-merge-restore-$SCOPE-$RUN_ID"
cleanup() {
  docker stop "$CONTAINER" > /dev/null 2>&1 || true
  rm -f "$DUMP.part" "$MEDIA.part"
}
trap cleanup EXIT
docker run --rm -d --network none --name "$CONTAINER" -e POSTGRES_DB=mskba_restore -e POSTGRES_PASSWORD="$(openssl rand -hex 32)" postgres:17-alpine > /dev/null
ready=false
for _attempt in $(seq 1 45); do
  # Official postgres entrypoint starts a temporary postmaster to initialize
  # the DB, then stops it before exec'ing the final server as PID 1.
  # pg_isready alone can return true during that temporary phase.
  if docker exec "$CONTAINER" sh -c 'test "$(cat /proc/1/comm)" = postgres' \
      && docker exec "$CONTAINER" pg_isready -q -U postgres -d mskba_restore; then
    ready=true
    break
  fi
  sleep 1
done
[[ "$ready" == true ]] || { echo 'Restore container failed to start' >&2; exit 4; }
if ! docker exec -i "$CONTAINER" pg_restore -U postgres -d mskba_restore --no-owner --no-acl --exit-on-error < "$DUMP" > "$DEST/restore.log" 2>&1; then
  echo 'Restore failed; see private restore.log on server' >&2
  exit 5
fi
chmod 600 "$DEST/restore.log"
source_migrations=$($COMPOSE exec -T db sh -ceu 'exec env PGPASSWORD="$POSTGRES_PASSWORD" psql -XAt -v ON_ERROR_STOP=1 -U "$POSTGRES_USER" -d "$POSTGRES_DB" -c "SELECT count(*) FROM migrations"')
restored_migrations=$(docker exec "$CONTAINER" psql -XAt -v ON_ERROR_STOP=1 -U postgres -d mskba_restore -c 'SELECT count(*) FROM migrations')
[[ "$source_migrations" == "$restored_migrations" ]] || { echo 'Restored migration count mismatch' >&2; exit 6; }

echo "REHEARSAL_OK scope=$SCOPE"
echo "restored_migrations=$restored_migrations"
for table in users teams tournaments games venues venue_courts; do
  count=$(docker exec "$CONTAINER" psql -XAt -v ON_ERROR_STOP=1 -U postgres -d mskba_restore -c "SELECT COUNT(*) FROM public.$table")
  printf 'restored.%s=%s\n' "$table" "$count"
done
echo "database_dump_bytes=$(stat -c %s "$DUMP")"
echo "media_archive_bytes=$(stat -c %s "$MEDIA")"
echo 'media_tar_integrity=OK'
if [[ "$SCOPE" == dev ]]; then
  # Exact leftover generated by the first failed rehearsal (not a user file).
  OLD_PART="$ROOT/43970685665/dev/storage-app.tar.gz.part"
  if [[ -f "$OLD_PART" && ! -L "$OLD_PART" ]]; then
    rm -f -- "$OLD_PART"
    echo 'old_incomplete_tar_cleaned=true'
  fi
fi
echo "private_backup_path=$DEST"
echo 'Source DBs not modified; no user rows or dumps uploaded to GitHub.'
